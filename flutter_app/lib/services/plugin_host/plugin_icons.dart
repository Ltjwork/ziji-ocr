/// 取白名单图标；未知名回退扩展图标（插件列表/入口永不因图标名缺字）。
IconData pluginIconOf(String? name) {
  if (name == null) return Icons.extension_outlined;
  return pluginIconWhitelist[name.trim().toLowerCase()] ??
      Icons.extension_outlined;
}
